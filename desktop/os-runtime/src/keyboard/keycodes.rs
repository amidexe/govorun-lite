//! Numeric OS codes, independent of keyboard layout or translated key labels.
use super::Platform;
use handy_keys::{Key, Modifiers};

pub(super) fn modifier(platform: Platform, key: u16) -> Option<Modifiers> {
    use Modifiers as M;
    Some(match (platform, key) {
        (Platform::MacOS, 54) | (Platform::Windows, 0x5C) => M::CMD_RIGHT,
        (Platform::MacOS, 55) | (Platform::Windows, 0x5B) => M::CMD_LEFT,
        (Platform::MacOS, 56) | (Platform::Windows, 0xA0) => M::SHIFT_LEFT,
        (Platform::MacOS, 60) | (Platform::Windows, 0xA1) => M::SHIFT_RIGHT,
        (Platform::MacOS, 58) | (Platform::Windows, 0xA4) => M::OPT_LEFT,
        (Platform::MacOS, 61) | (Platform::Windows, 0xA5) => M::OPT_RIGHT,
        (Platform::MacOS, 59) | (Platform::Windows, 0xA2) => M::CTRL_LEFT,
        (Platform::MacOS, 62) | (Platform::Windows, 0xA3) => M::CTRL_RIGHT,
        (Platform::MacOS, 63) => M::FN,
        _ => return None,
    })
}
